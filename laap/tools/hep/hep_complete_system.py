def component_tree_to_hep_spec(tree: Dict, style_id: str = "saas") -> Dict:
    """
    将 ComponentNode 树转换为 HEP 组件规格
    包含依赖关系解析
    """
    components = []

    # 添加主题组件
    components.append({
        "id": f"style.{style_id}",
        "params": {},
    })

    # 递归遍历组件树
    def walk(node: Dict):
        node_id = node.get("id", "")
        node_name = node.get("name", "")
        hep_id = node.get("hep_component_id") or f"component_{node_id}"

        # 处理子节点
        if node.get("children"):
            for child in node.get("children", []):
                walk(child)
        else:
            # 叶子节点 - 映射到 HEP 组件
            # 根据节点类型确定 HEP 组件 ID 和参数
            component_mapping = {
                # 页面布局组件
                "hero": ("ui.landing_page", {"title": "Generated Page"}),
                "header": ("ui.landing_page", {"title": "Header"}),
                "footer": ("ui.landing_page", {"title": "Footer"}),
                "navbar": ("ui.landing_page", {"title": "Navigation"}),
                "sidebar": ("ui.landing_page", {"title": "Sidebar"}),
                "content": ("ui.landing_page", {"title": "Main Content"}),

                # 内容组件
                "features": ("ui.landing_page", {"title": "Features"}),
                "testimonials": ("ui.landing_page", {"title": "Testimonials"}),
                "stats": ("ui.landing_page", {"title": "Statistics"}),
                "pricing": ("ui.landing_page", {"title": "Pricing"}),
                "faq": ("ui.landing_page", {"title": "FAQ"}),
                "contact": ("ui.landing_page", {"title": "Contact"}),
                "team": ("ui.landing_page", {"title": "Team"}),
                "gallery": ("ui.landing_page", {"title": "Gallery"}),
                "blog": ("ui.landing_page", {"title": "Blog"}),
                "portfolio": ("ui.landing_page", {"title": "Portfolio"}),

                # 表单组件
                "form": ("ui.landing_page", {"title": "Contact Form"}),
                "newsletter": ("ui.landing_page", {"title": "Newsletter Signup"}),
                "search": ("ui.landing_page", {"title": "Search Bar"}),

                # 按钮和链接
                "button": ("ui.landing_page", {"title": "Call to Action"}),
                "cta": ("ui.landing_page", {"title": "Call to Action Section"}),

                # 特殊组件 - 映射到后端服务
                "api": ("backend.fastapi_project", {"project_name": "Generated API"}),
                "database": ("db.postgres_schema", {"tables": [{"name": "items", "columns": [{"name": "id", "type": "int", "primary_key": True}, {"name": "name", "type": "str"}, {"name": "description", "type": "text"}]}]}),
                "auth": ("backend.fastapi_project", {"project_name": "Auth Service"}),
            }

            # 查找映射
            comp_key = node_id.lower().replace(" ", "_").replace("-", "_")
            if comp_key in component_mapping:
                hep_id, params = component_mapping[comp_key]
                # 合并节点参数
                params.update(node.get("params", {}))
            else:
                # 默认映射到通用页面组件
                hep_id = "ui.landing_page"
                params = {"title": node_name or "Generated Section"}
                params.update(node.get("params", {}))

            components.append({
                "id": hep_id,
                "params": params,
            })

    # 遍历树
    if tree:
        walk(tree)

    return {"components": components}

