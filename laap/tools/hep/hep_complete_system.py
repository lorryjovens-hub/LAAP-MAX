def build_project(user_intent: str, style: str = "saas",
                 output_dir: Optional[Path] = None) -> Dict[str, Any]:
    """
    一键构建项目的便捷函数

    Args:
        user_intent: 用户描述的需求（自然语言）
        style: 设计风格ID（如 "saas", "modern_dark", "cyberpunk"）
        output_dir: 可选的输出目录，如果提供则写入文件

    Returns:
        包含构建结果和生成产物的字典
    """
    system = CompleteHEPSystem()
    result = system.build_from_intent(user_intent, style)

    if output_dir and result["success"]:
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

        # 写入所有生成的文件
        for filename, content in result["artifacts"].items():
            if not filename.startswith("_"):  # 跳过元数据
                file_path = output_dir / filename
                file_path.parent.mkdir(parents=True, exist_ok=True)

                if isinstance(content, str):
                    file_path.write_text(content, encoding="utf-8")
                else:
                    # 对于二进制或特殊处理的内容
                    file_path.write_bytes(content) if isinstance(content, bytes) else \
                    file_path.write_text(str(content), encoding="utf-8")

        result["output_directory"] = str(output_dir.absolute())
        print(f"[HEP] Files written to: {output_dir.absolute()}")

    return result

