def _sql_type(py_type: str) -> str:
    """Python 类型到 SQL 类型的映射"""
    mapping = {
        "str": "VARCHAR(255)", "int": "INTEGER", "float": "REAL",
        "bool": "BOOLEAN", "datetime": "TIMESTAMP", "date": "DATE",
        "text": "TEXT", "bigint": "BIGINT"
    }
    return mapping.get(py_type.lower(), "VARCHAR(255)")

def _py_type(py_type: str) -> str:
    """Python 类型到 Pydantic 类型的映射"""
    mapping = {
        "str": "str", "int": "int", "float": "float",
        "bool": "bool", "datetime": "datetime", "date": "date",
        "list": "List[Any]", "dict": "Dict[str, Any]"
    }
    return mapping.get(py_type.lower(), "str")

