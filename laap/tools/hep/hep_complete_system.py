def gen_postgres_schema(tables: List[Dict]) -> str:
    """生成 PostgreSQL 数据库 schema"""
    sql = "-- PostgreSQL Schema Generated by HEP\n\n"

    for table in tables:
        table_name = table.get("name", "table")
        columns = table.get("columns", [])

        sql += f"CREATE TABLE {table_name} (\n"

        column_defs = []
        for col in columns:
            col_name = col.get("name", "column")
            col_type = col.get("type", "text")
            constraints = []

            if col.get("primary_key"):
                constraints.append("PRIMARY KEY")
            if not col.get("nullable", True):
                constraints.append("NOT NULL")
            if col.get("unique"):
                constraints.append("UNIQUE")
            if col.get("default"):
                constraints.append(f"DEFAULT {col['default']}")
            if col.get("check"):
                constraints.append(f"CHECK ({col['check']})")

            col_def = f"    {col_name} {_sql_type(col_type)}"
            if constraints:
                col_def += " " + " ".join(constraints)
            column_defs.append(col_def)

        # 添加外键
        foreign_keys = table.get("foreign_keys", [])
        for fk in foreign_keys:
            fk_def = f"    FOREIGN KEY ({fk['column']}) REFERENCES {fk['references_table']}({fk['references_column']})"
            if fk.get("on_delete"):
                fk_def += f" ON DELETE {fk['on_delete']}"
            if fk.get("on_update"):
                fk_def += f" ON UPDATE {fk['on_update']}"
            foreign_keys.append(fk_def)

        all_defs = column_defs + foreign_keys
        sql += ",\n".join(all_defs)
        sql += "\n);\n\n"

        # 添加索引
        indexes = table.get("indexes", [])
        for idx in indexes:
            idx_name = idx.get("name", f"idx_{table_name}_{idx['column']}")
            idx_unique = "UNIQUE " if idx.get("unique") else ""
            sql += f"CREATE {idx_unique}INDEX {idx_name} ON {table_name} ({idx['column']});\n"

        if indexes:
            sql += "\n"

    return sql

