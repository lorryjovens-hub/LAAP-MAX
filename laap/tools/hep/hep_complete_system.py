def gen_docker_compose(services: List[Dict]) -> str:
    """生成 docker-compose.yml"""
    compose = '''version: '3.8'

services:
'''

    for service in services:
        name = service.get("name", "service")
        image = service.get("image", "python:3.12-slim")
        ports = service.get("ports", [])
        environment = service.get("environment", {})
        volumes = service.get("volumes", [])
        depends_on = service.get("depends_on", [])

        compose += f"  {name}:\n"
        compose += f"    image: {image}\n"

        if ports:
            ports_str = "\n    ".join([f"- '{p}'" for p in ports])
            compose += f"    ports:\n    {ports_str}\n"

        if environment:
            env_str = "\n    ".join([f"{k}: {v}" for k, v in environment.items()])
            compose += f"    environment:\n    {env_str}\n"

        if volumes:
            vol_str = "\n    ".join([f"- {v}" for v in volumes])
            compose += f"    volumes:\n    {vol_str}\n"

        if depends_on:
            deps_str = "\n    ".join([f"- {d}" for d in depends_on])
            compose += f"    depends_on:\n    {deps_str}\n"

        command = service.get("command")
        if command:
            compose += f"    command: {command}\n"

        compose += "\n"

    return compose

