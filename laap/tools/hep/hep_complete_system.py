class CompleteHEPSystem:
    """完整 HEP 系统 - 集成所有功能"""

    def __init__(self):
        # 确保组件已注册
        register_hep_components()
        self.classifier = WebsiteClassifier()
        self.pipeline = HEPBuildPipeline(REGISTRY)

    def build_from_intent(self, user_intent: str, style_id: str = "saas") -> Dict[str, Any]:
        """
        从用户自然语言意图构建完整项目

        流程：
        1. 意图分类 → 网站类型 + 组件树
        2. 组件树 → HEP 组件规格（含依赖）
        3. HEP 规格 → 拓扑排序 → 依赖感知构建
        4. 返回多格式产物
        """
        start_time = time.time()

        # 步骤1: 意图分类
        print(f"[HEP] Analyzing intent: {user_intent}")
        blueprint = self.classifier.analyze(user_intent)
        print(f"[HEP] Detected type: {blueprint['type_name']} ({blueprint['display_name']})")

        # 步骤2: 转换为 HEP 规格
        print(f"[HEP] Converting component tree to HEP spec")
        hep_spec = component_tree_to_hep_spec(blueprint["tree"], style_id)
        print(f"[HEP] Generated {len(hep_spec['components'])} components")

        # 步骤3: 执行构建
        print(f"[HEP] Building components with dependency resolution")
        artifacts = self.pipeline.build(hep_spec)

        # 步骤4: 准备结果
        build_time = (time.time() - start_time) * 1000

        result = {
            "success": True,
            "intent": user_intent,
            "detected_type": blueprint["type_name"],
            "display_name": blueprint["display_name"],
            "style": style_id,
            "artifacts": artifacts,
            "build_time_ms": round(build_time, 2),
            "components_built": len([k for k in artifacts.keys() if not k.startswith("_")]),
            "metadata": artifacts.get("_meta", {})
        }

        print(f"[HEP] Build completed in {build_time:.2f}ms")
        print(f"[HEP] Generated {result['components_built']} artifacts")

        return result

    def build_from_spec(self, spec: Dict) -> Dict[str, Any]:
        """
        直接从 HEP 规格构建（跳过意图分类）
        """
        start_time = time.time()

        artifacts = self.pipeline.build(spec)

        build_time = (time.time() - start_time) * 1000

        return {
            "success": True,
            "artifacts": artifacts,
            "build_time_ms": round(build_time, 2),
            "components_built": len([k for k in artifacts.keys() if not k.startswith("_")]),
            "metadata": artifacts.get("_meta", {})
        }

    def list_available_components(self) -> Dict[str, List[str]]:
        """列出所有可用组件按域名分类"""
        return {domain: [comp.id for comp in REGISTRY.list_by_domain(domain)]
                for domain in ["ui", "backend", "database", "devops"]}

