def generate_hep(content, style_id, pagetype, title):
    composer = HEPComposer(REGISTRY)
    c = style_data.get(style_id, style_data["saas"])
    lines = content.strip().split("\n")
    title = title or "LAAP"
    sections = []
    cur = {"h": "", "b": ""}
    for line in lines:
        line = line.strip()
        if not line: continue
        if line.startswith("# "): title = line[2:].strip()
        elif line.startswith("## "):
            if cur["h"]: sections.append(cur)
            cur = {"h": line[3:].strip(), "b": ""}
        else:
            cur["b"] += ("\n" if cur["b"] else "") + line
    if cur["h"] or cur["b"]: sections.append(cur)

    theme = composer.compose({"components": [{"id": f"style.{style_id}", "params": {}}]})
