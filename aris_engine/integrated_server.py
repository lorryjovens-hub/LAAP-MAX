class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *a, **kw):
        super().__init__(*a, directory=str(SITE_DIR), **kw)

    def do_POST(self):
        length = int(self.headers.get("Content-Length", 0))
        try:
            data = json.loads(self.rfile.read(length).decode())
            if self.path == "/api/generate":
                html = generate_hep(data.get("content",""), data.get("style","saas"),
                                    data.get("pagetype","landing_page"), data.get("title",""))
                self._json(200, {"html": html, "length": len(html)})
            elif self.path == "/api/classify":
                t = data.get("intent","").lower()
                wtypes = {"shop": "ecommerce", "store": "ecommerce", "sell": "ecommerce",
                          "saas": "saas", "software": "saas", "portfolio": "portfolio",
                          "blog": "blog", "restaurant": "restaurant", "agency": "agency"}
                matched = "landing_page"
                for kw, wtype in wtypes.items():
                    if kw in t: matched = wtype; break
                self._json(200, {"type": matched, "display_name": matched.replace("_"," ").title()})
            else:
                self._json(404, {"error": "not found"})
        except Exception as e:
            self._json(500, {"error": str(e)})

    def _json(self, code, data):
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()
        self.wfile.write(json.dumps(data, ensure_ascii=False).encode())

    def do_OPTIONS(self):
        self.send_response(200)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "POST, GET, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()

    def do_GET(self):
        if self.path == "/api/status":
            self._json(200, {"components": len(REGISTRY._components),
                             "styles": len(style_data), "status": "running"})
        else:
            super().do_GET()


